#pragma once
#include <m5os/types.h>

/*
 * M5EX: M5OS executable format, version 1.  One relocatable blob, no symbol
 * tables, no imports (the kernel API is passed in as a table: m5ex_api.h).
 *
 *   file = header (64 bytes) | image (image_size) | relocation table (reloc_count * 4)
 *   all integers little-endian
 *
 *   header
 *     0  char[4]  magic "M5EX"
 *     4  u16      version (1)
 *     6  u16      header_size (64)
 *     8  u32      flags: bits 3..0 = target architecture (0 = Xtensa/ESP32-S3, 1 = RISC-V/ESP32-P4), others 0
 *    12  u32      api_version      minimum m5_api_t version the app needs
 *    16  u32      permissions      M5_PERM_* the app REQUESTS
 *    20  u32      image_size       bytes stored in the file after the header
 *    24  u32      mem_size         bytes of RAM to allocate (image + bss), >= image_size
 *    28  u32      code_size        [0, code_size) is code+literals; the rest is data
 *    32  u32      entry_offset     app_main(), inside the code part, 4-aligned
 *    36  u32      reloc_count
 *    40  u32      stack_size       task stack the app asks for
 *    44  u32      image_crc32      CRC-32 of image bytes followed by the relocation table
 *    48  char[16] name             NUL-terminated
 *
 *   The image is linked at address 0.  Each relocation entry is the offset of a
 *   32-bit word that holds a link-time address.  At load time the loader adds the
 *   real base: the I-bus alias if the word points into the code part (it will be
 *   jumped to), the D-bus address otherwise (it will be loaded from / stored to).
 *   The ESP32-S3 sees the same internal SRAM through both buses, which is what makes
 *   a single copy of the image usable for both.
 *
 * TRUST: the loader checks that the file is well-formed, not that the code is
 * harmless.  Loaded machine code runs with the kernel's full hardware access
 * (no MMU); the permission bits only govern the OS API.  Treat .m5ex files like
 * any program you would run.
 */
#define M5EX_MAGIC        "M5EX"
#define M5EX_VERSION      1u
#define M5EX_HEADER_SIZE  64u
/* Machine code is only valid for the CPU it was compiled for; the loader refuses any other. */
#define M5EX_ARCH_XTENSA  0u
#define M5EX_ARCH_RISCV   1u
#define M5EX_ARCH_MASK    0xFu
#include <m5os/board_config.h>
#ifdef M5OS_ARCH_RISCV
#  define M5EX_ARCH_THIS  M5EX_ARCH_RISCV
#else
#  define M5EX_ARCH_THIS  M5EX_ARCH_XTENSA
#endif
#define M5EX_MAX_MEM      (256u * 1024u)
#define M5EX_MIN_STACK    2048u
#define M5EX_MAX_STACK    16384u

typedef struct {
    char     magic[4];
    uint16_t version;
    uint16_t header_size;
    uint32_t flags;
    uint32_t api_version;
    uint32_t permissions;
    uint32_t image_size;
    uint32_t mem_size;
    uint32_t code_size;
    uint32_t entry_offset;
    uint32_t reloc_count;
    uint32_t stack_size;
    uint32_t image_crc32;
    char     name[16];
} m5ex_header_t;

_Static_assert(sizeof(m5ex_header_t) == M5EX_HEADER_SIZE, "M5EX header must be 64 bytes");

/* Check a complete file in memory.  Returns 0 or a negative ERR_*; on success *hdr is a copy of the header. */
int m5ex_validate(const uint8_t *file, size_t len, m5ex_header_t *hdr);

/* Load and start an app from a file (path) or from memory.  Same lifecycle as built-in apps. */
int app_start_file(const char *path, uint32_t *app_id);
int app_start_image(const uint8_t *file, size_t len, uint32_t *app_id);

/* Images compiled into the firmware (apps/m5ex/images.c, generated by tools/m5exbuild.py). */
typedef struct { const char *name; const uint8_t *data; uint32_t size; } m5ex_image_t;
const m5ex_image_t *m5ex_embedded(int *count);

bool m5ex_selftest(void);       /* needs the root filesystem mounted and the embedded images seeded */
