#!/usr/bin/env python3
"""Generate drivers/mjpeg/mjpeg_tables.inc: the JPEG standard Huffman tables (Annex K, which libjpeg and so
Pillow write by default) and the scaled-IDCT basis matrices.

Run from the repository root:  python tools/gen_mjpeg_tables.py
"""
import io
import math
import struct
from pathlib import Path

from PIL import Image


def dht_segments(jpeg: bytes):
    """Yield (class, id, bits[16], vals) for every table in the DHT segments of a JPEG."""
    i = 2
    while i + 4 <= len(jpeg):
        assert jpeg[i] == 0xFF
        marker = jpeg[i + 1]
        length = struct.unpack(">H", jpeg[i + 2:i + 4])[0]
        body = jpeg[i + 4:i + 2 + length]
        if marker == 0xC4:
            j = 0
            while j < len(body):
                tc_th = body[j]
                bits = list(body[j + 1:j + 17])
                n = sum(bits)
                vals = list(body[j + 17:j + 17 + n])
                yield tc_th >> 4, tc_th & 15, bits, vals
                j += 17 + n
        if marker == 0xDA:
            return
        i += 2 + length


def c_array(name, values, per_line=12):
    lines = []
    for k in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[k:k + per_line]) + ",")
    return f"static const uint8_t {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    img = Image.new("RGB", (16, 16), (90, 120, 200))
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=75, subsampling=2)  # default (non-optimized) tables = Annex K
    tables = {(tc, th): (bits, vals) for tc, th, bits, vals in dht_segments(buf.getvalue())}
    out = ["/* Generated by tools/gen_mjpeg_tables.py - do not edit.\n"
           " * Standard Huffman tables (ITU T.81 Annex K) used when an MJPEG frame carries no DHT segment, and the\n"
           " * N-point DCT basis (orthonormal, x2048) used for the scaled inverse DCT. */\n"]
    for (tc, th), label in (((0, 0), "dc_lum"), ((0, 1), "dc_chr"), ((1, 0), "ac_lum"), ((1, 1), "ac_chr")):
        bits, vals = tables[(tc, th)]
        out.append(c_array(f"std_{label}_bits", bits, 16))
        out.append(c_array(f"std_{label}_vals", vals, 12))
    for n in (2, 4, 8):
        rows = []
        for x in range(n):
            row = []
            for u in range(n):
                c = math.sqrt(1.0 / n) if u == 0 else math.sqrt(2.0 / n)
                row.append(round(2048 * c * math.cos((2 * x + 1) * u * math.pi / (2 * n))))
            rows.append("    {" + ", ".join(str(v) for v in row) + "},")
        out.append(f"static const int16_t idct_m{n}[{n}][{n}] = {{\n" + "\n".join(rows) + "\n};\n")
    path = Path("drivers/mjpeg/mjpeg_tables.inc")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print("wrote", path)


if __name__ == "__main__":
    main()
