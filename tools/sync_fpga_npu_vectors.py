"""Freeze carrier CPU arithmetic goldens. No wire protocol or RTL is generated."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import random
import subprocess
import sys

parser = argparse.ArgumentParser()
parser.add_argument("--carrier", type=Path, required=True)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
sys.dont_write_bytecode = True
carrier = args.carrier.resolve()
source = carrier / "fpga/reference/compute_reference.py"
spec = importlib.util.spec_from_file_location("carrier_compute", source)
gold = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gold)
rng = random.Random(20261028)
lines = ["/* Generated by tools/sync_fpga_npu_vectors.py from carrier CPU oracle. */", "#pragma once"]


def quant(q):
    return "{" + ",".join(map(str, q)) + "}"


def values(v):
    return "{" + ",".join(map(str, v)) + "}"


def outcome(fn):
    try:
        return 0, fn()
    except ValueError:
        return -1, 0
    except OverflowError:
        return -2, 0


lines += ["typedef struct {int32_t acc;fpga_npu_quant_t quant;int error,result;} npu_quant_case_t;",
          "static const npu_quant_case_t npu_quant_cases[]={"]
quant_cases = []
for shift in range(63):
    for acc in [-(1 << 31), -3, -1, 0, 1, 3, (1 << 31) - 1]:
        multiplier = rng.choice([0, 1, 3, (1 << 31) - 1])
        quant_cases.append((acc, [multiplier, shift, rng.choice([-128, 0, 127]), -128, 127]))
quant_cases += [(x, [1, 1, 0, -128, 127]) for x in [-5, -3, -1, 1, 3, 5]]
quant_cases += [(x, [1, 0, 17, 17, 127]) for x in [-100, -1, 0, 1, 100000]]
quant_cases += [(-2147483648, [2147483647, 62, -7, -7, 63]), (99, [123, 5, 0, 0, 0])]
quant_cases += [(7, q) for q in [[-1, 0, 0, -128, 127], [1, -1, 0, -128, 127],
                               [1, 63, 0, -128, 127], [1, 0, 128, -128, 127],
                               [1, 0, 0, 1, -1], [1, 0, 0, -129, 127]]]
for acc, q in quant_cases:
    error, result = outcome(lambda: gold.requantize(acc, *q))
    lines.append("{" + f"{acc},{quant(q)},{error},{result}" + "},")
lines.append("};")

lines += ["typedef struct {int32_t bias;int zero;fpga_npu_quant_t quant;unsigned count;fpga_npu_pair_t pairs[12];int error,result;} npu_dot_case_t;",
          "static const npu_dot_case_t npu_dot_cases[]={"]
dot_cases = [(0, 0, [1, 0, 0, -128, 127], []),
             (2147483647, 0, [1, 0, 0, -128, 127], [(1, 1)]),
             (-2147483648, 0, [1, 0, 0, -128, 127], [(1, -1)]),
             (3, 0, [1, 1, 0, -128, 127], []),
             (0, 128, [1, 0, 0, -128, 127], [(0, 1)]),
             (0, 0, [1, 0, 0, -128, 127], [(128, 1)]),
             (0, 0, [1, 0, 0, -128, 127], [(1, -129)])]
for _ in range(80):
    pairs = [(rng.randrange(-128, 128), rng.randrange(-128, 128)) for _ in range(rng.randrange(13))]
    dot_cases.append((rng.randrange(-100000, 100000), rng.randrange(-128, 128),
                      [rng.choice([0, 1, 17, 2147483647]), rng.randrange(63), rng.randrange(-128, 128), -128, 127], pairs))
for bias, zero, q, pairs in dot_cases:
    def dot():
        if not -128 <= zero <= 127:
            raise ValueError()
        acc = gold.tiled_gemm([[p[0] for p in pairs]], [[p[1]] for p in pairs], [bias], zero)[0][0] if pairs else bias
        return gold.requantize(acc, *q)
    error, result = outcome(dot)
    p = "{" + ",".join(values(pair) for pair in pairs) + "}" if pairs else "{{0,0}}"
    lines.append("{" + f"{bias},{zero},{quant(q)},{len(pairs)},{p},{error},{result}" + "},")
lines.append("};")

lines += ["typedef struct {unsigned m,k,n;int zero;int8_t a[64],b[64];int32_t bias[4],expected[16];int error;} npu_gemm_case_t;",
          "static const npu_gemm_case_t npu_gemm_cases[]={"]
gemm_count = 12
for case in range(gemm_count):
    m, k, n = rng.randrange(1, 5), rng.randrange(1, 9), rng.randrange(1, 5)
    a = [rng.randrange(-128, 128) for _ in range(m * k)]
    b = [rng.randrange(-128, 128) for _ in range(k * n)]
    zero = rng.choice([-128, 0, 127])
    bias = [rng.randrange(-10000, 10000) for _ in range(n)]
    if case == 0:
        m = k = n = 1; a = [1]; b = [1]; bias = [2147483647]; zero = 0
    error, result = outcome(lambda: gold.tiled_gemm([a[i*k:(i+1)*k] for i in range(m)],
        [b[i*n:(i+1)*n] for i in range(k)], bias, zero))
    expected = [v for row in result for v in row] if not error else [0]
    lines.append("{" + f"{m},{k},{n},{zero},{values(a)},{values(b)},{values(bias)},{values(expected)},{error}" + "},")
lines.append("};")

lines += ["typedef struct {fpga_npu_conv_t config;unsigned xc,wc,count;int8_t input[64],weights[64];int32_t bias[2],expected[128];int error;} npu_conv_case_t;",
          "static const npu_conv_case_t npu_conv_cases[]={"]
conv_count = 8
for case in range(conv_count):
    # Multiple channels, batches, asymmetric padding, stride and dilation.
    batch, ch, h, w, out, kh, kw = (2 if case == 6 else 1), 2, 3, 4, 2, 2, 2
    sy, sx, dy, dx = 1 + case % 2, 1 + (case // 2) % 2, 1 + case % 2, 1
    pt, pl, pb, pr = case % 2, (case // 2) % 2, 1, 0
    zero = rng.choice([-128, -3, 0, 127])
    x = [rng.randrange(-128, 128) for _ in range(batch * ch * h * w)]
    weights = [rng.randrange(-128, 128) for _ in range(out * ch * kh * kw)]
    bias = [rng.randrange(-10000, 10000) for _ in range(out)]
    if case == 0:
        x = [127] * len(x); weights = [127] * len(weights); bias = [2147483647] * out; zero = 0
    error, result = outcome(lambda: gold.conv2d(x, weights, (batch, ch, h, w), (out, ch, kh, kw),
        bias, (sy, sx), (pt, pl, pb, pr), (dy, dx), zero))
    expected = result[0] if not error else [0]
    config = [batch, ch, h, w, out, kh, kw, sy, sx, dy, dx, pt, pl, pb, pr, zero]
    lines.append("{" + f"{values(config)},{len(x)},{len(weights)},{len(expected)},{values(x)},{values(weights)},{values(bias)},{values(expected)},{error}" + "},")
lines.append("};")
content = "\n".join(lines) + "\n"
root = Path(__file__).resolve().parents[1]
header = root / "drivers/fpga/fpga_npu_vectors.h"
paths = ["fpga/reference/compute_reference.py", "fpga/npu/rtl/int8_mac_lane.v",
         "fpga/npu/rtl/int8_requantize.v", "fpga/npu/rtl/int8_dot_job.v"]
provenance = {"carrier_base_commit": subprocess.check_output(["git", "-C", str(carrier), "rev-parse", "HEAD"], text=True).strip(),
              "source_sha256": {p: hashlib.sha256((carrier / p).read_bytes()).hexdigest() for p in paths},
              "header_sha256": hashlib.sha256(content.encode()).hexdigest(),
              "cases": {"requant": len(quant_cases), "dot": len(dot_cases), "gemm": gemm_count, "conv": conv_count},
              "scope": "CPU arithmetic reference; no external NPU transport/bitstream contract exists"}
manifest = root / "tests/fixtures/fpga_npu_source.json"
metadata = json.dumps(provenance, indent=2) + "\n"
if args.check:
    if header.read_text() != content or manifest.read_text() != metadata:
        raise SystemExit("Carrier NPU arithmetic vectors or source hashes changed; review before syncing")
else:
    header.write_text(content, newline="\n")
    manifest.write_text(metadata, newline="\n")
print(json.dumps(provenance["cases"]))
